_COMPILED_TEMPLATES = tuple(
    (
        re.compile(
            "^" + re.escape(" ".join(source.split())).replace(
                r"\{\}", "(.*?)"
            ) + "$"
        ),
        target,
    )
    for source, target in _TEMPLATES
)


def get_language():
    return _language


def set_language(language):
    global _language
    if language not in (LANGUAGE_SPANISH, LANGUAGE_ENGLISH):
        raise ValueError(f"Unsupported language: {language}")
    _language = language


def toggle_language():
    set_language(
        LANGUAGE_ENGLISH
        if _language == LANGUAGE_SPANISH
        else LANGUAGE_SPANISH
    )


def _normalizar_clave(texto):
    """Ignora saltos de línea y espacios repetidos al comparar traducciones."""
    return " ".join(texto.split())


def translate(text):
    if _language == LANGUAGE_SPANISH or not isinstance(text, str):
        return text

    stripped = text.strip()
    leading_whitespace = text[: len(text) - len(text.lstrip())]
    trailing_whitespace = text[len(text.rstrip()) :]

    # Primero se intenta traducir el texto completo. Los saltos de línea
    # internos se consideran espacios únicamente durante la comparación.
    clave_normalizada = _normalizar_clave(stripped)

    for original, traduccion in _TRANSLATIONS.items():
        if _normalizar_clave(original) == clave_normalizada:
            return f"{leading_whitespace}{traduccion}{trailing_whitespace}"

    # También se normalizan los espacios antes de comprobar las plantillas.
    for pattern, template in _COMPILED_TEMPLATES:
        match = pattern.match(clave_normalizada)
        if match:
            translated = template.format(
                *(translate(value) for value in match.groups())
            )
            return f"{leading_whitespace}{translated}{trailing_whitespace}"

    # Si el texto completo no tiene traducción, se traducen sus líneas
    # individualmente, conservando los saltos de línea originales.
    if "\n" in stripped:
        translated = "\n".join(
            translate(line) for line in stripped.split("\n")
        )
        return f"{leading_whitespace}{translated}{trailing_whitespace}"

    return text



class LocalizedFont:
    def __init__(self, *args, **kwargs):
        self._font = pygame.font.Font(*args, **kwargs)

    def render(self, text, *args, **kwargs):
        return self._font.render(translate(text), *args, **kwargs)

    def __getattr__(self, name):
        return getattr(self._font, name)
